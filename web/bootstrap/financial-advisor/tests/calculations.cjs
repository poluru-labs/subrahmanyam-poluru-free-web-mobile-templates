const assert=require('node:assert/strict');
const c=require('../assets/js/calculations.js');
const near=(actual,expected)=>assert.ok(Math.abs(actual-expected)<.01,`${actual} != ${expected}`);
near(c.growth({initial:1000,monthly:100,years:1,rate:0,inflation:0}).balance,2200);
near(c.growth({initial:1000,monthly:0,years:1,rate:12,inflation:0}).balance,1126.825030);
near(c.growth({initial:1000,monthly:0,years:1,rate:-12,inflation:0}).balance,886.384872);
near(c.growth({initial:1000,monthly:0,years:1,rate:0,inflation:10}).real,909.090909);
near(c.loan({amount:1200,rate:0,years:1}).payment,100);
near(c.loan({amount:300000,rate:6,years:30}).payment,1798.651575);
const loan=c.loan({amount:300000,rate:6,years:30});
near(loan.rows.reduce((n,x)=>n+x.principal,0),300000);
near(loan.rows.at(-1).balance,0);
near(loan.total,loan.interest+300000);
near(c.savings({target:12000,existing:0,years:1,rate:0}).monthly,1000);
near(c.savings({target:100,existing:200,years:1,rate:0}).monthly,0);
near(c.education({years:1,cost:10000,study:4,inflation:0,existing:0,rate:0}).target,40000);
near(c.education({years:1,cost:10000,study:2,inflation:10,existing:0,rate:0}).target,23100);
assert.throws(()=>c.retirement({age:65,retirementAge:60,initial:0,monthly:0,rate:5,inflation:2,spending:0}));
assert.throws(()=>c.growth({initial:-1,monthly:100,years:1,rate:0}));
assert.throws(()=>c.growth({initial:0,monthly:100,years:0,rate:0}));
assert.throws(()=>c.loan({amount:100,rate:-1,years:1}));
console.log('PASS: 17 independent calculation and boundary checks.');
